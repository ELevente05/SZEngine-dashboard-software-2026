// Safe Little Endian Parser
inline int16_t parseLE(const uint8_t* data, int offset) { 
  uint16_t raw_val = static_cast<uint16_t>(data[offset]) | (static_cast<uint16_t>(data[offset + 1]) << 8);
  //return static_cast<int16_t>(raw_val); 
  return raw_val;
}

